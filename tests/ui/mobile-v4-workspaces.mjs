import assert from 'node:assert/strict';
import process from 'node:process';
import {spawn} from 'node:child_process';
import {setTimeout as wait} from 'node:timers/promises';
import {chromium} from 'playwright';
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','4185','--strictPort'],{stdio:'ignore'});
const url='http://127.0.0.1:4185/mobile-audit-browser.html?surface=';
let browser,checks=0;
const eq=(a,b,m)=>{assert.equal(a,b,m);checks++;};
const ok=(v,m)=>{assert.ok(v,m);checks++;};
try {
  for(let i=0;i<70;i++){try{if((await fetch(url+'trades')).ok)break;}catch{}await wait(200);}
  browser=await chromium.launch({headless:true,channel:'chrome'});
  for(const [width,height] of [[360,740],[393,852],[430,932],[690,360]]) {
    const page=await browser.newPage({viewport:{width,height}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(url+'trades');
    const root=page.locator('[data-mobile-workspace-v4]');await root.waitFor();
    eq(await page.locator('[data-v4-trade-card]').count(),2,'positions have distinct new rows');
    eq(await page.evaluate(()=>document.activeElement?.tagName==='INPUT'),false,'opening Trades never opens keyboard');
    const p1=page.locator('[data-v4-trade-card="positions:p1"]');
    await p1.getByRole('button',{name:/Details for/}).click();
    ok((await p1.textContent()).includes('Commission'),'expanded position shows actual costs');
    await p1.getByRole('button',{name:'Manage on chart'}).click();
    await page.waitForFunction(()=>window.mobileSurfacesQA.destination?.id==='p1');
    eq(await page.evaluate(()=>window.mobileSurfacesQA.commands.length),0,'chart handoff sends no command');
    await p1.getByRole('button',{name:'Close',exact:true}).click();
    eq(await page.evaluate(()=>window.mobileSurfacesQA.commands.length),0,'close is confirmed inline');
    await p1.getByRole('button',{name:'Back',exact:true}).click();
    eq(await page.getByRole('group',{name:'Confirm trade action'}).count(),0,'Back discards only local confirmation');
    if(width===393)await page.screenshot({path:'artifacts/mobile-v4-trades-redesigned.png'});
    await p1.getByRole('button',{name:'Close',exact:true}).click();
    await p1.getByRole('button',{name:'Confirm',exact:true}).dblclick();
    await page.waitForFunction(()=>window.mobileSurfacesQA.commands.length===1);
    eq(await page.locator('[data-v4-trade-card]').count(),2,'accepted position stays until snapshot');
    await page.evaluate(()=>window.mobileSurfacesQA.acknowledge());
    await p1.waitFor({state:'detached'});
    eq(await page.locator('[data-v4-trade-card]').count(),1,'snapshot removes closed position');
    await page.getByRole('tab',{name:/^Pending/}).click();
    const pending=page.locator('[data-v4-trade-card="pending:o1"]');
    await pending.getByRole('button',{name:/Details for/}).click();
    ok((await pending.textContent()).includes('GTC'),'pending details expose expiry');
    await pending.getByRole('button',{name:'Manage on chart'}).click();
    await page.waitForFunction(()=>window.mobileSurfacesQA.destination?.kind==='pending');
    await pending.getByRole('button',{name:'Cancel order'}).click();
    await pending.getByRole('button',{name:'Confirm',exact:true}).click();
    await page.waitForFunction(()=>window.mobileSurfacesQA.commands.length===2);
    eq(await pending.count(),1,'pending cancellation is not optimistic');
    await page.evaluate(()=>window.mobileSurfacesQA.acknowledge());await pending.waitFor({state:'detached'});
    await page.getByRole('tab',{name:'History',exact:true}).click();
    await page.getByRole('combobox',{name:'History period'}).selectOption('all');
    eq(await page.locator('[data-v4-trade-card]').count(),2,'all-time closed positions include both instruments');
    await page.getByRole('combobox',{name:'History instrument'}).selectOption('EURUSD');
    eq(await page.locator('[data-v4-trade-card]').count(),1,'history instrument filter works');
    const history=page.locator('[data-v4-trade-card="position:h1"]');
    await history.getByRole('button',{name:/Details for/}).click();
    ok((await history.textContent()).includes('Exit'),'closed-position details show execution prices');
    await history.getByRole('button',{name:'View on chart'}).click();
    await page.waitForFunction(()=>window.mobileSurfacesQA.destination?.kind==='history');
    if(width===393)await page.screenshot({path:'artifacts/mobile-v4-history-redesigned.png'});
    await page.getByRole('tab',{name:'Orders',exact:true}).click();
    eq(await page.locator('[data-v4-trade-card]').count(),1,'order history excludes active pending orders');
    ok((await page.locator('[data-v4-trade-card]').textContent()).includes('cancelled'),'cancelled order status shown instead of zero profit');
    await page.getByRole('combobox',{name:'History period'}).selectOption('custom');
    eq(await page.evaluate(()=>document.activeElement?.tagName==='INPUT'),false,'custom dates do not autofocus');
    await page.getByLabel('History start date').fill('2026-10-20');await page.getByLabel('History end date').fill('2026-10-01');
    await page.getByRole('alert').waitFor();
    ok((await page.getByRole('alert').textContent()).includes('Start date'),'invalid range is explained');
    await page.getByRole('combobox',{name:'History period'}).selectOption('all');
    await page.evaluate(()=>window.mobileSurfacesQA.setHistoryLoaded(false));
    await page.getByRole('status').waitFor();
    ok((await page.getByRole('status').textContent()).includes('Loading'),'loading is distinct from empty');
    await page.evaluate(()=>window.mobileSurfacesQA.setHistoryError('Sync failed'));
    await page.getByRole('button',{name:'Retry history'}).click();
    await page.locator('[data-v4-trade-card]').waitFor();
    eq(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Trades/History fit width');
    await page.goto(url+'accounts');
    await page.locator('[data-v4-account-overview]').waitFor();
    eq(await page.locator('[data-v4-account-margin]').count(),1,'new account layout separates margin breakdown');
    eq(await page.locator('[data-v4-account-switcher] button').count(),2,'new account switcher lists both accounts');
    await page.getByRole('button',{name:'Switch to ACG-SECOND',exact:true}).click();
    await page.waitForFunction(()=>window.mobileSurfacesQA.selected==='second');
    eq(await page.getByRole('button',{name:'Switch to ACG-SECOND',exact:true}).getAttribute('aria-pressed'),'true','selected account remains controlled by supplied account state');
    await page.getByRole('button',{name:'Account details',exact:true}).click();
    ok((await root.textContent()).includes('Account ID'),'account details disclose ID/currency/leverage');
    if(width===393)await page.screenshot({path:'artifacts/mobile-v4-accounts-redesigned.png'});
    await page.getByRole('button',{name:'Settings',exact:true}).click();
    await page.waitForFunction(()=>window.mobileSurfacesQA.destination?.kind==='settings');
    await page.getByRole('button',{name:'Help & support',exact:true}).click();
    await page.waitForFunction(()=>window.mobileSurfacesQA.destination?.kind==='help');
    eq(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Accounts fits width');
    eq(await page.evaluate(()=>document.activeElement?.tagName==='INPUT'),false,'account actions do not open keyboard');
    eq(errors.length,0,'no runtime errors: '+errors.join(';'));
    await page.close();
  }
  console.log('MOBILE_V4_WORKSPACES_PASS',checks);
}finally{if(browser)await browser.close();server.kill();}
