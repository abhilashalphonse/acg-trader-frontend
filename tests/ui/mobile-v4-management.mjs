    await page.mouse.move(box.x+20,box.y+40,{steps:4});await page.mouse.up();
    eq(await accepted.evaluate(el=>el.style.top),originalTop,'accepted level stays fixed during edit');
    eq(await page.evaluate(()=>window.mobileManageQA.commands.length),0,'drag release sends no command');
    eq(await page.evaluate(()=>window.mobileManageQA.positions[0].volume),0.1,'SL edit preserves filled volume');
    await dock.getByRole('button',{name:'Discard',exact:true}).click();
    eq(await page.locator('[data-mobile-v4-proposed-line]').count(),0,'discard removes local preview');
    eq(await page.evaluate(()=>window.mobileManageQA.commands.length),0,'discard sends no command');
    // Drag the accepted SL directly, then apply. The simulated account deliberately
    // withholds the snapshot to prove HTTP acceptance does not move the solid line.
    const sl=page.locator('[data-mobile-v4-badge="fixture-account:position:p1:sl"]');
    const slbox=await sl.boundingBox();
    await page.mouse.move(slbox.x+20,slbox.y+18);await page.mouse.down();
    await page.mouse.move(slbox.x+20,slbox.y+38,{steps:4});await page.mouse.up();
    await dock.getByRole('button',{name:'Apply SL',exact:true}).click();
    await page.waitForFunction(()=>window.mobileManageQA.commands.length===1);
    eq(await accepted.evaluate(el=>el.style.top),originalTop,'accepted price awaits account snapshot');
    await page.waitForFunction(()=>document.querySelector('[data-acg-mobile-manage-dock]')?.textContent.includes('Waiting for account confirmation'));
    ok((await dock.textContent()).includes('Waiting for account confirmation'),'waiting state shown in dock');
    await page.evaluate(()=>window.mobileManageQA.acknowledge());
    await page.waitForFunction(()=>!window.mobileManageQA.management.edit);
    ok((await accepted.evaluate(el=>el.style.top))!==originalTop,'snapshot replaces accepted level');
    if(width===393)await page.screenshot({path:'artifacts/mobile-v4-position-management.png'});
    await dock.getByRole('button',{name:'Trade actions'}).click();
    await dock.getByRole('button',{name:'Remove SL',exact:true}).click();
    eq(await page.evaluate(()=>window.mobileManageQA.commands.length),1,'removal requires confirmation');
    await dock.getByRole('button',{name:'Confirm',exact:true}).click();
