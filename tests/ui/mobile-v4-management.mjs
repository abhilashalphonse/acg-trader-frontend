    eq(await page.evaluate(()=>document.activeElement?.tagName==='INPUT'),false,'selection never opens keyboard');
    await dock.getByRole('button',{name:'SL ✓',exact:true}).click();
    await page.locator('[data-mobile-v4-badge="draft"]').waitFor();
