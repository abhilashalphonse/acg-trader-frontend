    await page.evaluate(()=>window.mobileManageQA.acknowledge());
    await accepted.waitFor({state:'detached'});
    await dock.getByRole('button',{name:'Finish managing trade'}).click();
    await page.locator('[data-manage-idle]').waitFor();
    const pending=page.locator('[data-mobile-v4-badge="fixture-account:pending:o1:entry"]');
